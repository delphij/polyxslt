// Generates docs/SUPPORTED.md from the instruction and function registries, and
// docs/ERRORS.md from src/errors.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';

const bundle = await build({
  stdin: {
    contents: `export { instructions } from './src/xslt/compile';
      export { functions } from './src/xslt/runtime';
      export { coreFunctions } from './src/xpath/fn';`,
    resolveDir: '.',
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  write: false,
  define: { __DEV__: 'true' },
  logLevel: 'error',
});
const mod = await import(
  `data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`
);

const list = (names) =>
  [...names]
    .sort()
    .map((n) => `\`${n}\``)
    .join(', ');
const core = [...mod.coreFunctions.keys()];
const xslt = [...mod.functions.keys()].filter((n) => !mod.coreFunctions.has(n));
// The elements of XSLT 1.0; those without an entry in the registry are listed as not
// supported.
const XSLT_ELEMENTS = [
  'apply-imports',
  'apply-templates',
  'attribute',
  'attribute-set',
  'call-template',
  'choose',
  'comment',
  'copy',
  'copy-of',
  'decimal-format',
  'element',
  'fallback',
  'for-each',
  'if',
  'import',
  'include',
  'key',
  'message',
  'namespace-alias',
  'number',
  'param',
  'preserve-space',
  'processing-instruction',
  'sort',
  'strip-space',
  'text',
  'value-of',
  'variable',
  'with-param',
];
for (const n of mod.instructions.keys()) {
  if (!XSLT_ELEMENTS.includes(n)) throw new Error(`xsl:${n} is missing from XSLT_ELEMENTS`);
}
const unsupported = XSLT_ELEMENTS.filter((n) => !mod.instructions.has(n));

writeFileSync(
  'docs/SUPPORTED.md',
  `# Supported features

Generated by \`pnpm docs:gen\` from the registries in the source; do not edit.

| Area | Supported |
|---|---|
| Top-level elements | \`xsl:stylesheet\`, \`xsl:transform\`, \`xsl:template\` (\`match\`, \`priority\`; named templates are accepted but cannot be called), \`xsl:variable\`, \`xsl:output\` (\`method\`) |
| Instructions | ${list(mod.instructions.keys())}, literal result elements with attribute value templates |
| XPath functions | ${list(core)} |
| XSLT functions | ${list(xslt)} |
| Output methods | \`html\`, \`xml\`, \`text\` |

Not supported: ${list(unsupported.map((n) => `xsl:${n}`))}, reported as error 20 like
any other element that is not known; the \`mode\` attribute, attribute sets, other output
methods and the \`namespace\` axis, reported as error 2; and the XSLT functions not listed
above, reported as error 12. See [DIVERGENCES.md](DIVERGENCES.md) for differences in behavior.
`,
);

const src = readFileSync('src/errors.ts', 'utf8');
const codes = [...src.matchAll(/^\s+(\w+) = (\d+),$/gm)].map(([, name, n]) => [name, Number(n)]);
const messages = new Map(
  [...src.matchAll(/\[Code\.(\w+)\]: '([^']*)'/g)].map(([, name, m]) => [name, m]),
);
writeFileSync(
  'docs/ERRORS.md',
  `# Error codes

Generated by \`pnpm docs:gen\` from src/errors.ts; do not edit.

Errors are thrown as \`XSLTError\` with a numeric \`code\`. Production builds carry only the
code; development builds (\`dist/dev\`) also carry the message below and details.

| Code | Name | Meaning |
|---|---|---|
${codes.map(([name, n]) => `| ${n} | ${name} | ${messages.get(name) ?? ''} |`).join('\n')}
`,
);
console.log('docs/SUPPORTED.md and docs/ERRORS.md written');
